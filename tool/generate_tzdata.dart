import 'dart:io';

import 'package:essentia/essentia.dart' hide Platform;
import 'package:essentia/src/time/internal/zone_data_codec.dart';

part '_zic_rule.dart';
part '_zic_source.dart';
part '_zic_time.dart';
part '_zic_zone_line.dart';

/// The release of the time zone database in `third_party/tzdata`.
const release = '2026e';

/// The files of the release that hold zones, rules and links, as the
/// database builds by default.
const sources = <String>[
  'africa',
  'antarctica',
  'asia',
  'australasia',
  'europe',
  'northamerica',
  'southamerica',
  'etcetera',
  'backward',
];

/// The generated file.
const output = 'lib/src/time/internal/tzdata.dart';

/// How many characters of zone data one string literal holds.
const _chunk = 64;

/// Compiles the time zone database into [output], or with `--check` only
/// tells whether [output] is current, exiting with 1 when it is not.
Future<void> main(List<String> arguments) async {
  final bool check = arguments.contains('--check');
  final source = ZicSource.parse(<String>[
    for (final String name in sources)
      File('third_party/tzdata/$release/$name').readAsStringSync(),
  ]);
  final String generated = await _formatted(render(release, source));
  final file = File(output);
  if (!check) {
    file.writeAsStringSync(generated);
    stdout.writeln('Wrote $output (${source.zones.length} zones).');
    return;
  }
  if (!file.existsSync() || file.readAsStringSync() != generated) {
    stderr.writeln(
      '$output is out of date: run dart run tool/generate_tzdata.dart',
    );
    exitCode = 1;
    return;
  }
  stdout.writeln('$output is current.');
}

/// The Dart source of the database [version] compiled from [source].
String render(String version, ZicSource source) {
  final List<String> zoneIds = source.zones.keys.toList()..sort();
  final linkIds = <String>[
    for (final String link in source.links.keys)
      if (!source.zones.containsKey(link)) link,
  ]..sort();
  final out = StringBuffer()
    ..writeln(
      File('tool/license_header.txt')
          .readAsStringSync()
          .replaceAll('{year}', '2026'),
    )
    ..writeln('/// The time zone database $version, generated by')
    ..writeln('/// `tool/generate_tzdata.dart` from the release in')
    ..writeln('/// `third_party/tzdata`. Do not edit.')
    ..writeln('@internal')
    ..writeln('library;')
    ..writeln()
    ..writeln("import 'package:meta/meta.dart';")
    ..writeln()
    ..writeln('/// The version of the database.')
    ..writeln("const tzdataVersion = '$version';")
    ..writeln()
    ..writeln('/// The canonical zone identifiers, sorted.')
    ..writeln('const tzdataZoneIds = <String>[');
  for (final id in zoneIds) {
    out.writeln("  '$id',");
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('/// The rules of each zone of [tzdataZoneIds], in the compact')
    ..writeln('/// format, in pieces to join.')
    ..writeln('const tzdataZoneData = <List<String>>[');
  for (final id in zoneIds) {
    final String data = encodeZone(source.compile(id));
    final chunks = <String>[
      for (var start = 0; start < data.length; start += _chunk)
        data.substring(
          start,
          start + _chunk > data.length ? data.length : start + _chunk,
        ),
    ];
    out.writeln("  <String>[${chunks.map((chunk) => "'$chunk'").join(', ')}],");
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('/// The identifiers that link to a canonical zone, sorted.')
    ..writeln('const tzdataLinkIds = <String>[');
  for (final id in linkIds) {
    out.writeln("  '$id',");
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln(
      '/// The index in [tzdataZoneIds] each link of [tzdataLinkIds] points',
    )
    ..writeln('/// at.')
    ..writeln('const tzdataLinkTargets = <int>[');
  for (final id in linkIds) {
    out.writeln('  ${zoneIds.indexOf(source.canonical(id))},');
  }
  out.writeln('];');
  return out.toString();
}

/// [source] as `dart format` writes it.
Future<String> _formatted(String source) async {
  final Directory directory = Directory.systemTemp.createTempSync('tzdata');
  try {
    final file = File('${directory.path}/tzdata.dart')
      ..writeAsStringSync(source);
    final ProcessResult result = await Process.run(
      Platform.resolvedExecutable,
      <String>['format', file.path],
    );
    if (result.exitCode != 0) {
      throw StateError('dart format failed: ${result.stderr}');
    }
    return file.readAsStringSync();
  } finally {
    directory.deleteSync(recursive: true);
  }
}
